#!/usr/bin/env python3
"""Inject the latest payload JSON produced by build.py into the redesigned index.html template."""
import argparse
import json
import re
from pathlib import Path


def main():
    p = argparse.ArgumentParser(description="Inject build.py payload into redesigned dashboard HTML.")
    p.add_argument("--source", default="build/index.html", help="HTML generated by build.py containing fresh #payload")
    p.add_argument("--template", default="build/templates/redesign_template.html", help="Redesigned index.html template")
    p.add_argument("--output", default="index.html", help="Final output HTML for GitHub Pages")
    args = p.parse_args()

    src_html = Path(args.source).read_text(encoding="utf-8")
    tpl_html = Path(args.template).read_text(encoding="utf-8")

    m_payload = re.search(r'<script[^>]*id="payload"[^>]*>(.*?)</script>', src_html, re.S)
    if not m_payload:
        raise SystemExit(f"Error: could not find <script id='payload'> in {args.source}")
    fresh_payload_str = m_payload.group(1).strip()
    payload = json.loads(fresh_payload_str)

    out_html, n_sub = re.subn(
        r'(<script[^>]*id="payload"[^>]*>)(.*?)(</script>)',
        lambda m: m.group(1) + fresh_payload_str + m.group(3),
        tpl_html,
        count=1,
        flags=re.S,
    )
    if n_sub != 1:
        raise SystemExit(f"Error: could not find <script id='payload'> in {args.template}")

    price_bar = payload.get("priceBar")
    if price_bar:
        out_html = re.sub(
            r'價量：美東\s*\d{4}-\d{2}-\d{2}',
            f'價量：{price_bar}',
            out_html,
            count=1,
        )

    out_path = Path(args.output)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(out_html, encoding="utf-8")
    print(f"Updated {out_path} ({len(payload.get('stocks', []))} stocks, priceBar={price_bar})")


if __name__ == "__main__":
    main()
